"""Builds data/audit.js (the Audit section of the site) from the audit inputs/outputs and data/audit_decisions.json.
Usage: python3 -I tools/audit_site.py WORK_DIR"""
import glob, json, os, sys

W = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data')
PART = {'I': 'Public inventory', 'N': 'Notice & explanation', 'A': 'Impact assessment, testing & monitoring', 'H': 'Human review & appeal',
        'V': 'Vendor & developer duties', 'O': 'Oversight body & enforcement', 'SCOPE': 'Scope'}
ins, qa, ra, cc = {}, {}, [], []
for f in sorted(glob.glob(os.path.join(W, 'audit_in_*.json'))):
    for e in json.load(open(f)):
        ins[e['key']] = e
for f in sorted(glob.glob(os.path.join(W, 'audit_out_*.json'))):
    d = json.load(open(f))
    for r in d['quote_audit']:
        qa[r['qid']] = r
    ra += d['rating_audit']
    cc += d['claim_checks']
dec = json.load(open(os.path.join(DATA, 'audit_decisions.json')))
quotes = {q['qid']: (e, q) for e in ins.values() for q in e['quotes']}
name = lambda k: '%s %s' % (ins[k]['state'], ins[k]['bill']) if k in ins else k

stats = {
    'quotes': len(quotes), 'exact': sum(1 for _, q in quotes.values() if q['exact_match_in_text']),
    'ok': sum(1 for r in qa.values() if r['severity'] == 'OK'), 'minor': sum(1 for r in qa.values() if r['severity'] == 'MINOR'),
    'major': sum(1 for r in qa.values() if r['severity'] == 'MAJOR'),
    'labelWrong': sum(1 for r in qa.values() if r['where_correct'] == 'no'), 'notSupported': sum(1 for r in qa.values() if r['supports_claim'] == 'No'),
    'ratingsReviewed': len(ra), 'ratingsDisagree': sum(1 for r in ra if r['agree'] == 'no'),
    'ratingsApplied': sum(1 for v in dec['ratings'].values() if v.startswith('APPLIED')),
    'ratingsNotApplied': sum(1 for v in dec['ratings'].values() if v.startswith('NOT applied')),
    'claims': len(cc), 'claimsWrong': sum(1 for c in cc if c['verified'] == 'no'), 'claimsOutside': sum(1 for c in cc if c['verified'] == 'unverifiable'),
    'caveats': sum(1 for r in qa.values() if [f for f in r['context_flags'] if f not in ('NOT_ENACTED_VERSION', 'OTHER')] or (r['severity'] != 'OK' and r['comment']))}
rating_changes = []
for k, v in dec['ratings'].items():
    if v.startswith('APPLIED') or v.startswith('NOT applied'):
        key, part = k.split('|')
        rating_changes.append({'entry': name(key), 'part': PART.get(part, part), 'action': v})
quote_changes = []
for qid, v in dec['quotes'].items():
    if v.startswith('DROPPED') or 'corrected' in v:
        e, q = quotes[qid]
        quote_changes.append({'entry': name(e['key']), 'part': PART.get(q['part'], q['part']), 'where': q['where'], 'action': v,
                              'why': qa[qid]['comment'] if v.startswith('DROPPED') or 'corrected' in v else ''})
claim_fixes = [{'entry': name(c['key']), 'claim': c['claim'], 'evidence': c['evidence']} for c in cc if c['verified'] == 'no']
out = {'stats': stats, 'ratingChanges': rating_changes, 'quoteChanges': quote_changes, 'claimFixes': claim_fixes}
with open(os.path.join(DATA, 'audit.js'), 'w', encoding='utf-8') as fh:
    fh.write('/* Generated by tools/audit_site.py */\nwindow.AUDIT=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(stats, len(rating_changes), len(quote_changes), len(claim_fixes))
