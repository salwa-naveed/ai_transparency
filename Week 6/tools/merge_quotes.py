"""Merges verified quotes into data/quotes.js.
Usage: python3 -I tools/merge_quotes.py WORK_DIR
WORK_DIR holds assign.json, texts/<KEY>.txt, texts/<KEY>.json (from tools/fetch_texts.py) and quotes_*.json.
Every quote is re-checked against the bill text (letters and digits only, case-insensitive); unverified quotes are dropped.
Output: window.QUOTES = { "STATE|bill label": { meta:{...}, q:[{part, supported, quote, where, specifics, note}] } }"""
import glob, json, os, re, sys

W = sys.argv[1]
FED_URL = {
    'FED_M-25-21': 'https://www.whitehouse.gov/wp-content/uploads/2025/02/M-25-21-Accelerating-Federal-Use-of-AI-through-Innovation-Governance-and-Public-Trust.pdf',
    'FED_M-25-22': 'https://www.whitehouse.gov/wp-content/uploads/2025/02/M-25-22-Driving-Efficient-Acquisition-of-Artificial-Intelligence-in-Government.pdf',
}


def norm(s):
    s = s.replace('’', "'").replace('‘', "'").replace('–', '-').replace('—', '-').lower()
    return re.sub(r'[^a-z0-9]', '', s)


SKIP = {'UT_HB320', 'HI_SB59'}   # entries dropped after text review
assign = {a['key']: a for a in json.load(open(os.path.join(W, 'assign.json'))) if a['key'] not in SKIP}
hay = {}
for k, a in assign.items():
    parts = []
    for f in a['files']:
        p = os.path.join(W, 'texts', f)
        if os.path.exists(p):
            parts.append(norm(open(p, encoding='utf-8', errors='replace').read()))
    hay[k] = ''.join(parts)

out = {}
dropped = 0
kept = 0
for f in sorted(glob.glob(os.path.join(W, 'quotes_*.json'))):
    for r in json.load(open(f)):
        k = r['key']
        if k not in assign:
            continue
        a = assign[k]
        label = a['state'] + '|' + a['bill']
        e = out.setdefault(label, {'meta': {}, 'q': []})
        if r.get('quote') and norm(r['quote']) not in hay[k]:
            dropped += 1
            print('DROPPED (not in text):', k, r.get('part'), r['quote'][:60])
            continue
        e['q'].append({x: r.get(x, '') for x in ('part', 'supported', 'quote', 'where', 'specifics', 'note')})
        kept += 1

for k, a in assign.items():
    label = a['state'] + '|' + a['bill']
    jp = os.path.join(W, 'texts', k + '.json')
    meta = {}
    if os.path.exists(jp):
        j = json.load(open(jp))
        ts = j.get('texts') or []
        t = sorted(ts, key=lambda t: (t['date'], t['doc_id']))[-1] if ts else {}
        meta = {'version': t.get('type', ''), 'date': (t.get('date', '') if str(t.get('date', ''))[:4] > '1999' else ''), 'textUrl': t.get('url', ''),
                'stateUrl': t.get('state_link', ''), 'legiscan': j.get('url', ''), 'status': j.get('status'),
                'statusDate': j.get('status_date', '')}
    elif k in FED_URL:
        meta = {'version': 'Official memo (PDF)', 'date': '2025', 'textUrl': FED_URL[k], 'stateUrl': '', 'legiscan': ''}
    out.setdefault(label, {'meta': {}, 'q': []})['meta'] = meta

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, '..', 'data', 'quotes.js'), 'w', encoding='utf-8') as fh:
    fh.write('/* Generated by tools/merge_quotes.py. Quotes are copied from the bill or memo text and re-verified by script; use Ctrl+F on the linked text to cross-check. */\n')
    fh.write('window.QUOTES=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('kept', kept, 'dropped', dropped, 'entries', len(out))
